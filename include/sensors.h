static const char* const DISPLAY_DIGITS[10] = {
    DISPLAY_ONE,
    DISPLAY_TWO,
    DISPLAY_THREE,
    DISPLAY_FOUR,
    DISPLAY_FIVE,
    DISPLAY_SIX,
    DISPLAY_SEVEN,
    DISPLAY_EIGHT,
    DISPLAY_NINE,
    DISPLAY_ZERO,
};

static const char* DISPLAY_STATE = DISPLAY_EMPTY;

static inline void update_display_state(uint8_t n)
{
    DISPLAY_STATE = (n >= 0 || n <= 9) ? DISPLAY_DIGITS[n] : DISPLAY_ERROR;
}

static inline void usart3_ssegment_state()
{
    for (int i = 0; i < COLUMNS * ROWS; i++)
    {
        while (!(USART3_SR & USART_SR_TXE)) {}
        USART3_DR = (uint32_t)DISPLAY_STATE[i];
        if (i % COLUMNS == COLUMNS - 1)
        {
            while (!(USART3_SR & USART_SR_TXE)) {}
            USART3_DR = (uint32_t)'\n';
        }
    }
}

// ROUTER

static inline bool exec_command(const message_in_t* message_in)
{
    switch (message_in->cmd)
    {
        case CMD_SSEGMENT:
            update_display_state(message_in->args[0]);
            usart3_ssegment_state();
            return true;
        default:
            return false;
    }

    // unreachable
    return false;
}